const szerokoscTekstu = s => [...s].length * SZER - 1;

/* rysuje tekst; opcje: wyr ('lewo' | 'srodek' | 'prawo'), cien (kolor cienia), skala */
function tekst(g, s, x, y, kolor = '#fff', opcje = {}) {
  const sk = opcje.skala || 1;
  const szer = szerokoscTekstu(s) * sk;
  if (opcje.wyr === 'srodek') x -= Math.floor(szer / 2);
  else if (opcje.wyr === 'prawo') x -= szer;
  x = Math.round(x); y = Math.round(y);
  const rysuj = (kx, ky, k) => {
    g.fillStyle = k;
    let cx = kx;
    for (const ch of s) {
      const gl = GLIFY[ch] || GLIFY[ch.toUpperCase()] || Z['?'];
      const start = gl[0];
      for (let r = 1; r < gl.length; r++) {
        const w = gl[r];
        for (let c = 0; c < 5; c++) if (w[c] === '1') g.fillRect(cx + c * sk, ky + (start + r - 1) * sk, sk, sk);
      }
      cx += SZER * sk;
    }
  };
  if (opcje.cien) rysuj(x + sk, y + sk, opcje.cien);
  rysuj(x, y, kolor);
  return szer;
}

/* łamanie tekstu na linie o maksymalnej szerokości (w pikselach) */
function lamTekst(s, maxSzer) {
  const linie = [];
  for (const akapit of s.split('\n')) {
    let linia = '';
    for (const slowo of akapit.split(' ')) {
      const proba = linia ? linia + ' ' + slowo : slowo;
      if (szerokoscTekstu(proba) > maxSzer && linia) { linie.push(linia); linia = slowo; }
      else linia = proba;
    }
    linie.push(linia);
  }
  return linie;
}

